"""Check that the pinned dependency lock is a faithful resolution of the requirements.

``backend/requirements.txt`` declares the runtime dependencies of the platform as
version *ranges*, because a range is what a human maintains: it says which
major version the project is written against and leaves the exact build to the
resolver. ``backend/requirements.lock`` is the *resolution* of that declaration:
every dependency, including the transitive ones, pinned to one exact version and
carrying the hashes of the distributions that version was published as.

The lock is what the container image installs, with ``--require-hashes``, so a
build either reproduces the recorded artefact exactly or fails. The lock is
generated by ``pip-compile`` and must therefore be regenerated whenever a
declared range changes.

Nothing checks that automatically, so a lock can silently rot: a requirement is
added, widened or tightened in ``requirements.txt`` and the pipeline keeps
installing the old resolution. This script closes that gap. It verifies that

* every declared requirement appears in the lock,
* the locked version still satisfies the declared range,
* every locked entry carries at least one SHA-256 hash,
* every locked entry is reachable from a declared requirement, so the lock
  carries no package that nothing needs any more, and
* every dependency edge the lock records names a package the lock contains.

The check is deliberately offline. It reads two files in the repository and
never contacts a package index, so it cannot be influenced by what the index
happens to serve at the moment it runs. The completeness of the lock is proved
by the pipeline itself, which installs it with ``--require-hashes``: pip
refuses to install a lock that is missing a package or that carries an
unhashed entry.

Safety note
-----------
This script reads two files and writes nothing. It never builds, publishes or
contacts any external service.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from packaging.requirements import InvalidRequirement, Requirement
from packaging.specifiers import InvalidSpecifier, SpecifierSet
from packaging.utils import canonicalize_name

__all__ = [
    "DeclaredRequirement",
    "LockedPackage",
    "check_lock",
    "main",
    "parse_lock",
    "parse_requirements",
]


REPO_ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS_FILE = REPO_ROOT / "backend" / "requirements.txt"
LOCK_FILE = REPO_ROOT / "backend" / "requirements.lock"

#: A line that opens a new entry in the lock file.
_ENTRY_PATTERN = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)"
    r"(?:\[[^\]]*\])?"
    r"==(?P<version>[^\s\\;]+)"
)

#: A hash option on a lock entry.
_HASH_PATTERN = re.compile(r"--hash=sha256:(?P<digest>[0-9a-f]{64})\b")

#: The comment that opens the provenance block of a lock entry.
_VIA_HEADER_PATTERN = re.compile(r"^\s*#\s*via\b\s*(?P<inline>.*)$")

#: A continuation line of a multi-parent provenance block. The entry is either
#: the name of a package or a reference to the requirements file itself.
_VIA_ITEM_PATTERN = re.compile(r"^\s*#\s{2,}(?P<item>\S.*?)\s*$")


@dataclass(frozen=True)
class DeclaredRequirement:
    """A dependency declared in ``backend/requirements.txt``."""

    name: str
    specifier: SpecifierSet
    extras: tuple[str, ...]

    @property
    def canonical_name(self) -> str:
        """The normalised name, as PEP 503 defines it."""
        return canonicalize_name(self.name)


@dataclass(frozen=True)
class LockedPackage:
    """A package pinned in ``backend/requirements.lock``."""

    name: str
    version: str
    hashes: tuple[str, ...]
    required_by: tuple[str, ...]

    @property
    def canonical_name(self) -> str:
        """The normalised name, as PEP 503 defines it."""
        return canonicalize_name(self.name)


def _iter_content_lines(text: str) -> list[str]:
    """Return the lines of a requirements file that carry a requirement."""
    lines: list[str] = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            lines.append(line)
    return lines


def parse_requirements(text: str) -> dict[str, DeclaredRequirement]:
    """Parse the declared requirements of ``backend/requirements.txt``.

    Every requirement is parsed with the reference implementation of the
    requirement grammar, so a malformed declaration is reported rather than
    silently skipped.
    """
    declared: dict[str, DeclaredRequirement] = {}
    for line in _iter_content_lines(text):
        try:
            requirement = Requirement(line)
        except InvalidRequirement as exc:
            raise ValueError(
                f"the declaration '{line}' is not a valid requirement: {exc}"
            ) from exc
        try:
            specifier = SpecifierSet(str(requirement.specifier))
        except InvalidSpecifier as exc:
            raise ValueError(
                f"the declaration '{line}' has an invalid version range: {exc}"
            ) from exc
        canonical = canonicalize_name(requirement.name)
        if canonical in declared:
            raise ValueError(
                f"the requirement '{requirement.name}' is declared more than once"
            )
        declared[canonical] = DeclaredRequirement(
            name=requirement.name,
            specifier=specifier,
            extras=tuple(sorted(requirement.extras)),
        )
    return declared


def parse_lock(text: str) -> dict[str, LockedPackage]:
    """Parse the pinned packages of ``backend/requirements.lock``.

    The format is the one ``pip-compile --generate-hashes`` writes: one entry
    per package, opening with the exact version, followed by the hashes of the
    distributions of that version and closed by a provenance comment that
    names the packages that require it.
    """
    locked: dict[str, LockedPackage] = {}
    name: str | None = None
    version: str | None = None
    hashes: list[str] = []
    required_by: list[str] = []
    in_via = False

    def close() -> None:
        if name is None or version is None:
            return
        canonical = canonicalize_name(name)
        if canonical in locked:
            raise ValueError(f"the lock pins '{name}' more than once")
        locked[canonical] = LockedPackage(
            name=name,
            version=version,
            hashes=tuple(hashes),
            required_by=tuple(required_by),
        )

    for raw in text.splitlines():
        entry = _ENTRY_PATTERN.match(raw)
        if entry is not None:
            close()
            name = entry.group("name")
            version = entry.group("version")
            hashes = []
            required_by = []
            in_via = False
            continue

        if name is None:
            continue

        digest = _HASH_PATTERN.search(raw)
        if digest is not None:
            hashes.append(digest.group("digest"))
            continue

        via_header = _VIA_HEADER_PATTERN.match(raw)
        if via_header is not None:
            in_via = True
            inline = via_header.group("inline").strip()
            if inline:
                required_by.append(inline)
            continue

        if in_via:
            via_item = _VIA_ITEM_PATTERN.match(raw)
            if via_item is not None:
                required_by.append(via_item.group("item"))

    close()
    return locked


def _is_a_direct_declaration(parent: str) -> bool:
    """Tell whether a provenance entry names the requirements file itself."""
    return parent.startswith("-r ") or parent.startswith("-c ")


def check_lock(
    declared: dict[str, DeclaredRequirement],
    locked: dict[str, LockedPackage],
) -> list[str]:
    """Compare the declared requirements with the lock and report every problem.

    The returned list is empty when the lock is a faithful resolution. Each
    entry names one problem and is safe to print.
    """
    problems: list[str] = []

    for canonical, requirement in sorted(declared.items()):
        package = locked.get(canonical)
        if package is None:
            problems.append(
                f"'{requirement.name}' is declared in requirements.txt but is not in the lock"
            )
            continue
        if not package.hashes:
            problems.append(f"the lock pins '{package.name}' without a single hash")
        if requirement.specifier and not requirement.specifier.contains(
            package.version, prereleases=True
        ):
            problems.append(
                f"the lock pins '{package.name}' at {package.version}, "
                f"which does not satisfy the declared range {requirement.specifier}"
            )
        if not any(_is_a_direct_declaration(parent) for parent in package.required_by):
            problems.append(
                f"the lock does not record '{package.name}' as a declared requirement"
            )

    for package in locked.values():
        if not package.hashes:
            problems.append(f"the lock pins '{package.name}' without a single hash")

    # A package that the lock records as a root is one that the requirements
    # file declares. A root that nothing declares means the lock carries a
    # requirement that has been removed.
    roots = {
        package.canonical_name
        for package in locked.values()
        if any(_is_a_direct_declaration(parent) for parent in package.required_by)
    }
    for canonical in sorted(roots - set(declared)):
        problems.append(
            f"the lock records '{locked[canonical].name}' as a declared requirement, "
            "but requirements.txt does not declare it"
        )

    # Every locked package has to be reachable from a root, and every
    # dependency edge has to name a package the lock actually contains.
    reachable = set(roots)
    pending = list(roots)
    while pending:
        current = pending.pop()
        for package in locked.values():
            if package.canonical_name in reachable:
                continue
            if any(
                canonicalize_name(parent) == current for parent in package.required_by
            ):
                reachable.add(package.canonical_name)
                pending.append(package.canonical_name)

    for canonical, package in sorted(locked.items()):
        if canonical not in reachable:
            problems.append(
                f"the lock pins '{package.name}', which no declared requirement reaches"
            )
        for parent in package.required_by:
            if _is_a_direct_declaration(parent):
                continue
            parent_canonical = canonicalize_name(parent)
            if parent_canonical not in locked:
                problems.append(
                    f"the lock records '{package.name}' as required by '{parent}', "
                    "which the lock does not contain"
                )

    return problems


def main(argv: list[str]) -> int:
    """Check the lock of the repository and report the outcome."""
    parser = argparse.ArgumentParser(
        description="Check that the dependency lock is a faithful resolution of the requirements."
    )
    parser.add_argument(
        "--requirements",
        type=Path,
        default=REQUIREMENTS_FILE,
        help="the declared requirements file to check against",
    )
    parser.add_argument(
        "--lock",
        type=Path,
        default=LOCK_FILE,
        help="the lock file to check",
    )
    args = parser.parse_args(argv)

    try:
        declared = parse_requirements(args.requirements.read_text())
        locked = parse_lock(args.lock.read_text())
    except (OSError, ValueError) as exc:
        print(f"the dependency lock could not be read: {exc}", file=sys.stderr)
        return 1

    problems = check_lock(declared, locked)

    if problems:
        print(
            f"The dependency lock {args.lock} does not match {args.requirements}.",
            file=sys.stderr,
        )
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        print(
            "Regenerate the lock with "
            "'pip-compile --generate-hashes --strip-extras "
            "--output-file=backend/requirements.lock backend/requirements.txt'.",
            file=sys.stderr,
        )
        return 1

    print(
        f"The dependency lock is a faithful resolution: {len(declared)} declared "
        f"requirements, {len(locked)} pinned packages, every one hashed."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
